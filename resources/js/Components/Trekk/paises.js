export const ARGENTINA = PAISES[0][0];

export const caracteristicaDe = (pais) => PAISES.find(([nombre]) => nombre === pais)[1];

// "+542974280000" -> Argentina y "2974280000". Sin característica se toma como número de Argentina.
export function separarTelefono(telefono) {
    const limpio = (telefono ?? '').replace(/[^\d+]/g, '');
    const encontrado = limpio.startsWith('+')
        ? PAISES.find(([, caracteristica]) => limpio.startsWith(caracteristica))
        : undefined;

    if (!encontrado) {
        return { pais: ARGENTINA, numero: limpio.replace(/\D/g, '') };
    }

    const [pais, caracteristica] = encontrado;
    const numero = limpio.slice(caracteristica.length);

    // El 9 de los celulares argentinos no forma parte de los 10 números
    return { pais, numero: pais === ARGENTINA && numero.length === 11 ? numero.replace(/^9/, '') : numero };
}
